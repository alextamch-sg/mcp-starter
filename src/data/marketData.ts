// Helper to generate realistic candles and sparklines
function generateCandles(basePrice: number, count: number = 30, volatility: number = 0.015): Candle[] {
  const candles: Candle[] = [];
  let currentPrice = basePrice * (1 - (Math.random() * 0.05 - 0.025));
  const now = new Date();

  for (let i = count; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
    const change = currentPrice * (Math.random() * volatility * 2 - volatility);
    const open = currentPrice;
    const close = Math.max(0.01, open + change);
    const high = Math.max(open, close) + Math.random() * currentPrice * (volatility * 0.6);
    const low = Math.min(open, close) - Math.random() * currentPrice * (volatility * 0.6);
    const volume = Math.floor(Math.random() * 50000000 + 10000000);

    candles.push({
      time: dateStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
    currentPrice = close;
  }
  return candles;
}

function candlesToSparkline(candles: Candle[]): number[] {
  return candles.map(c => c.close);
}

